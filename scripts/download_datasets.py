def main() -> int:
    ap = argparse.ArgumentParser(
        description="Download, extract, generate and verify all RAVANA datasets.")
    ap.add_argument("--force", action="store_true",
                    help="re-download / re-extract (overwrites existing files)")
    ap.add_argument("--only", nargs="+", default=None, metavar="NAME",
                    help="only these datasets (aliases allowed)")
    ap.add_argument("--skip", nargs="+", default=None, metavar="NAME",
                    help="skip these datasets (aliases allowed)")
    ap.add_argument("--verify-only", action="store_true",
                    help="only run verification, never download/extract")
    ap.add_argument("--yes", action="store_true",
                    help="don't prompt for large downloads")
    args = ap.parse_args()

    wanted = resolve_names(args.only, strict=True) if args.only else list(DATASETS)
    skipped = set(resolve_names(args.skip or [], strict=False))
    wanted = [w for w in wanted if w not in skipped]

    print("=" * 68)
    print("  RAVANA dataset downloader")
    print(f"  target: {DATA}")
    print("=" * 68)

    # ── Download phase ──
    if not args.verify_only:
        big = {"glove": 823_000_000, "conceptnet": 498_000_000,
               "lancaster": 17_000_000}
        missing_big = [k for k in wanted if k in big and not _already_have(k)]
        if missing_big and not (args.yes or args.force):
            total = sum(big[k] for k in missing_big)
            print(f"\n  About to download ~{total/1e6:.0f} MB more "
                  f"({', '.join(missing_big)}).")
            try:
                r = input("  Continue? [y/N] ").strip().lower()
            except EOFError:
                r = "n"
            if r not in ("y", "yes"):
                print("  Aborted by user.")
                return 1

        dl_fails = []
        for name in wanted:
            print(f"\n[{name}]")
            dl, _ = DATASETS[name]
            try:
                dl(args.force)
            except Exception as e:
                print(f"  [ERROR] {name}: {e}")
                dl_fails.append(name)
        if dl_fails:
            print(f"\n  DOWNLOAD FAILURES: {', '.join(dl_fails)}")
            print("  (continuing to verify the rest; a plain re-run retries failed files)")
    else:
        dl_fails = []
        print("\n  (download phase skipped)")

    # ── Verify phase ──
    print("\n" + "=" * 68)
    print("  VERIFICATION")
    print("=" * 68)
    fails = []
    for name in wanted:
        _, verify = DATASETS[name]
        try:
            ok, detail = verify()
        except Exception as e:
            ok, detail = False, f"exception: {e}"
        status = "PASS" if ok else "FAIL"
        print(f"  {status:4s}  {name:12s} {detail}")
        if not ok:
            fails.append(name)

    print("=" * 68)
    if fails:
        print(f"  RESULT: {len(fails)} FAILURES: {', '.join(fails)}")
        print("  (re-run with --force to repair)")
        return 1
    if dl_fails:
        print(f"  RESULT: ALL PASS but {len(dl_fails)} download failures: '"
              f"{', '.join(dl_fails)}'")
        return 1
    print("  RESULT: ALL PASS")
    print("=" * 68)
    return 0


def _already_have(name: str) -> bool:
    """Cheap existence check used only for the download-size prompt."""
    if name == "glove":
        return os.path.exists(os.path.join(DATA, "glove", "glove.6B.100d.txt"))
    if name == "conceptnet":
        return os.path.exists(os.path.join(DATA, "conceptnet", "en_assertions.tsv"))
    if name == "lancaster":
        return os.path.exists(os.path.join(DATA, "cache", "word_ratings",
                                           "Lancaster_sensorimotor_norms_for_39707_words.csv"))
    return False


