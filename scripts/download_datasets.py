def _v_logiqa() -> Tuple[bool, str]:
    n = 0
    for split in ("Eval", "Test"):
        path = os.path.join(DATA, "benchmarks", "logiqa", f"{split}.txt")
        if not os.path.exists(path):
            return False, f"{split}.txt missing"
        blocks = open(path, encoding="latin-1").read().strip().split("\n\n")
        good = sum(1 for b in blocks if len(b.strip().split("\n")) >= 7)
        n += good
        if good == 0:
            return False, f"{split}.txt has 0 valid blocks"
    return True, f"{n} valid blocks (Eval+Test)"


def _v_timedial() -> Tuple[bool, str]:
    path = os.path.join(DATA, "benchmarks", "timedial", "test.json")
    if not os.path.exists(path):
        return False, "missing"
    td = json.load(open(path, encoding="utf-8"))
    need = {"correct1", "correct2", "incorrect1", "incorrect2", "conversation"}
    ok = isinstance(td, list) and len(td) > 1000 and all(need <= set(x) for x in td[:5])
    return ok, f"{len(td)} dialogs"


def _v_locomo() -> Tuple[bool, str]:
    path = os.path.join(DATA, "benchmarks", "locomo", "locomo10.json")
    if not os.path.exists(path):
        return False, "missing"
    lc = json.load(open(path, encoding="utf-8"))
    first = lc[0].get("conversation", {}) if lc else {}
    has_sessions = any(str(k).startswith("session_") for k in first)
    n_qa = len(lc[0].get("qa", [])) if lc else 0
    ok = isinstance(lc, list) and len(lc) == 10 and has_sessions and n_qa > 0
    return ok, f"{len(lc)} convs, sessions={has_sessions}, dlg0 qa={n_qa}"


def _v_longmemeval() -> Tuple[bool, str]:
    path = os.path.join(DATA, "benchmarks", "longmemeval", "longmemeval_oracle.json")
    if not os.path.exists(path):
        return False, "missing"
    lme = json.load(open(path, encoding="utf-8"))
    need = {"question", "answer", "question_type", "haystack_sessions", "haystack_dates"}
    ok = isinstance(lme, list) and len(lme) == 500 and need <= set(lme[0])
    return ok, f"{len(lme)} items"


def _v_advbench() -> Tuple[bool, str]:
    path = os.path.join(DATA, "benchmarks", "advbench", "harmful_behaviors.csv")
    if not os.path.exists(path):
        return False, "missing"
    rows = list(csv.DictReader(open(path, encoding="utf-8")))
    ok = len(rows) > 500 and "goal" in rows[0]
    return ok, f"{len(rows)} behaviors"


def _v_memfail() -> Tuple[bool, str]:
    specs = {
        "coexisting_facts_dataset.csv": "preference_facts",
        "conditional_facts_dataset_easy.csv": "entity_facts",
        "conditional_facts_dataset_hard.csv": "entity_facts",
        "long_hop_chains.csv": "fact_1",
        "persona_dataset.csv": "entity_facts",
    }
    details = []
    for fn, col in specs.items():
        path = os.path.join(DATA, "benchmarks", "memfail", fn)
        if not os.path.exists(path):
            return False, f"{fn} missing"
        rows = list(csv.DictReader(open(path, encoding="utf-8")))
        if not (len(rows) > 0 and col in rows[0]):
            return False, f"{fn}: missing column {col!r}"
        details.append(f"{fn}:{len(rows)}")
    return True, ", ".join(details)


def _v_glove() -> Tuple[bool, str]:
    out = []
    for name in ("glove.6B.100d.txt", "glove.6B.50d.txt"):
        p = os.path.join(DATA, "glove", name)
        ok = os.path.exists(p) and os.path.getsize(p) > 100_000_000
        out.append(f"{name}:{'OK' if ok else 'MISSING'}")
    return all("OK" in o for o in out), " ".join(out)


def _v_conceptnet() -> Tuple[bool, str]:
    p = os.path.join(DATA, "conceptnet", "en_assertions.tsv")
    if not os.path.exists(p) or os.path.getsize(p) < 100_000_000:
        return False, "en_assertions.tsv missing/short"
    bad = 0
    n = 0
    with open(p, encoding="utf-8") as f:
        for line in f:
            parts = line.rstrip("\n").split("\t")
            if len(parts) < 4:
                bad += 1
            elif not (parts[0].startswith("/r/")
                      and parts[1].startswith("/c/en/")
                      and parts[2].startswith("/c/en/")):
                bad += 1
            n += 1
            if n >= 200_000:
                break
    return bad == 0, f"{n:,} lines sampled, {bad} bad"


