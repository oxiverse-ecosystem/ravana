CHUNK = 1 << 20  # 1 MiB


# ─────────────────────────────────────────────────────────────────────────────
# Download helpers (resumable, progress, retries)
# ─────────────────────────────────────────────────────────────────────────────

def _download(url: str, dest: str, label: str = "", retries: int = 3) -> int:
    """Download ``url`` to ``dest``, resuming a partial file via HTTP Range.

    Returns bytes written. The caller (``fetch``) has already decided whether
    the file needs (re-)downloading, so this only handles the transfer.
    """
    os.makedirs(os.path.dirname(dest) or ".", exist_ok=True)
    size_before = os.path.getsize(dest) if os.path.exists(dest) else 0

    for attempt in range(retries):
        try:
            headers = dict(UA)
            if size_before > 0:
                headers["Range"] = f"bytes={size_before}-"
            req = urllib.request.Request(url, headers=headers)
            resp = urllib.request.urlopen(req, timeout=120)
            total = int(resp.headers.get("Content-Length", 0))
            if resp.status == 206:
                total += size_before
            elif size_before > 0:
                # Server ignored the Range header — restart from scratch.
                size_before = 0
                resp.close()
                req = urllib.request.Request(url, headers=UA)
                resp = urllib.request.urlopen(req, timeout=120)
                total = int(resp.headers.get("Content-Length", 0))

            mode = "ab" if (size_before > 0 and resp.status == 206) else "wb"
            written = size_before if mode == "ab" else 0
            t0 = time.time()
            last_pct = -1
            with open(dest, mode) as f:
                while True:
                    chunk = resp.read(CHUNK)
                    if not chunk:
                        break
                    f.write(chunk)
                    written += len(chunk)
                    if total:
                        pct = int(written * 100 / total)
                        if pct != last_pct and (pct % 10 == 0 or pct == 100):
                            last_pct = pct
                            mb = written / 1e6
                            speed = written / 1e6 / max(time.time() - t0, 1e-9)
                            print(f"    [{label}] {pct:3d}%  {mb:8.1f} MB  {speed:6.1f} MB/s")
            resp.close()
            return written
        except (urllib.error.URLError, TimeoutError, OSError) as e:
            size_before = os.path.getsize(dest) if os.path.exists(dest) else 0
            if attempt < retries - 1:
                print(f"    [{label}] attempt {attempt + 1} failed ({e}); retrying...")
                time.sleep(2 * (attempt + 1))
            else:
                raise RuntimeError(f"download failed for {label}: {e}") from e
    return 0  # unreachable


def fetch(url: str, dest: str, label: str = "", min_bytes: int = 0,
          force: bool = False) -> None:
    """Fetch a file if missing/short (or always when ``force``)."""
    if force and os.path.exists(dest):
        os.remove(dest)
    if os.path.exists(dest) and os.path.getsize(dest) >= min_bytes:
        return
    print(f"  [fetch] {label}: {url}")
    _download(url, dest, label=label)
    if os.path.getsize(dest) < min_bytes:
        raise RuntimeError(f"{label}: downloaded file is too small "
                           f"({os.path.getsize(dest)} < {min_bytes} bytes)")


