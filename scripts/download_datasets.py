"""
download_datasets.py — one-shot download, extract, generate & verify for ALL
RAVANA datasets.

Reproduces the exact data layout the codebase expects under ``data/``:

    data/corpora/tiny_shakespeare.txt        (Karpathy char-rnn input.txt)
    data/corpora/teen_seeds.txt              (generated by gather_teen_seeds.py)
    data/glove/glove.6B.{100d,50d}.txt       (from Stanford glove.6B.zip)
    data/cache/word_ratings/Lancaster_sensorimotor_norms_for_39707_words.csv
    data/conceptnet/en_assertions.tsv        (English subset of ConceptNet 5.7)
    data/benchmarks/logiqa/{Eval,Test}.txt
    data/benchmarks/timedial/test.json
    data/benchmarks/locomo/locomo10.json
    data/benchmarks/longmemeval/longmemeval_oracle.json
    data/benchmarks/advbench/harmful_behaviors.csv
    data/benchmarks/memfail/*.csv            (5 MemFail files)
    data/benchmarks_external/locomo10.json            (copy, for eval_longmem.py)
    data/benchmarks_external/longmemeval_oracle_50.jsonl (derived, for eval_longmem.py)

NOTE: Binder et al. (2016) ``WordSet1_Ratings.xlsx`` is intentionally NOT
included — no public direct-download URL could be located. It is optional:
the engine falls back to the downloaded Lancaster probe when it is absent.

Stdlib only (urllib / zipfile / gzip / json / csv / subprocess) — no pip
dependencies. Idempotent: existing verified files are skipped unless --force.
Downloads are resumable (HTTP Range) and verify each file's format after
fetching.

Usage:
    python scripts/download_datasets.py                 # download what's missing, verify all
    python scripts/download_datasets.py --force         # re-download + re-extract everything
    python scripts/download_datasets.py --only glove    # one dataset
    python scripts/download_datasets.py --verify-only   # just run format checks
    python scripts/download_datasets.py --skip teen_seeds conceptnet
"""

