def extract_glove(zip_path: str, out_dir: str, targets: List[str],
                  force: bool = False) -> None:
    """Extract only the needed members of glove.6B.zip."""
    with zipfile.ZipFile(zip_path) as zf:
        names = zf.namelist()
        for t in targets:
            out = os.path.join(out_dir, t)
            if force and os.path.exists(out):
                os.remove(out)
            if os.path.exists(out) and os.path.getsize(out) > 0:
                print(f"  [glove] {t} already extracted")
                continue
            if t not in names:
                raise RuntimeError(f"{t} not in {zip_path}")
            print(f"  [glove] extracting {t} ...")
            zf.extract(t, out_dir)


def extract_conceptnet_english(gz_path: str, out_tsv: str,
                               force: bool = False) -> int:
    """Filter the full ConceptNet 5.7 dump to English assertions.

    Source format (tab-separated):
        assertion_id | relation | start | end | metadata-json
    Ravana's parsers (ConceptNetOntology.from_tsv, build_semantic_seed.py)
    expect:
        relation | start | end | metadata-json
    """
    if force and os.path.exists(out_tsv):
        os.remove(out_tsv)
    if os.path.exists(out_tsv) and os.path.getsize(out_tsv) > 50_000_000:
        print(f"  [conceptnet] {os.path.basename(out_tsv)} already built")
        return 0
    print("  [conceptnet] extracting English assertions "
          "(this streams ~475 MB, takes a few minutes)...")
    count = 0
    t0 = time.time()
    with gzip.open(gz_path, "rt", encoding="utf-8", errors="replace") as fin, \
            open(out_tsv, "w", encoding="utf-8") as fout:
        for line in fin:
            parts = line.rstrip("\n").split("\t")
            if len(parts) < 5:
                continue
            rel, start, end = parts[1], parts[2], parts[3]
            if start.startswith("/c/en/") and end.startswith("/c/en/"):
                fout.write("\t".join([rel, start, end, parts[4]]) + "\n")
                count += 1
                if count % 1_000_000 == 0:
                    el = time.time() - t0
                    print(f"    ...{count:,} assertions ({el:.0f}s)")
    print(f"  [conceptnet] wrote {count:,} English assertions -> {out_tsv}")
    return count


def make_longmemeval_50(oracle_json: str, out_jsonl: str, limit: int = 50,
                        force: bool = False) -> None:
    """Derive the 50-line JSONL subset eval_longmem.py expects."""
    if force and os.path.exists(out_jsonl):
        os.remove(out_jsonl)
    if os.path.exists(out_jsonl) and os.path.getsize(out_jsonl) > 0:
        print(f"  [longmemeval] {os.path.basename(out_jsonl)} already built")
        return
    data = json.load(open(oracle_json, encoding="utf-8"))
    with open(out_jsonl, "w", encoding="utf-8") as f:
        for item in data[:limit]:
            f.write(json.dumps({
                "question_id": item.get("question_id"),
                "question_type": item.get("question_type"),
                "question": item.get("question"),
                "answer": item.get("answer"),
                "haystack_sessions": item.get("haystack_sessions", []),
                "haystack_dates": item.get("haystack_dates", []),
            }) + "\n")
    print(f"  [longmemeval] wrote {limit}-line JSONL -> {out_jsonl}")


