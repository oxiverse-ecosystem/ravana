# invocation, or those two, to populate it.


def resolve_names(names: List[str], strict: bool) -> List[str]:
    """Map CLI names (aliases allowed) to canonical dataset keys.

    ``strict``: raise if nothing resolved (used for --only).
    Non-strict (used for --skip): unknown/empty means skip nothing.
    """
    out = []
    for n in names:
        n = n.strip().lower()
        match = [k for k, syns in ALIASES.items() if n in syns]
        if not match:
            print(f"  [warn] unknown dataset '{n}'; known: {', '.join(DATASETS)}")
            continue
        out.append(match[0])
    if strict and not out:
        raise SystemExit("no valid dataset names given")
    return out


